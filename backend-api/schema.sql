create table if not exists public.frame_detection_count_table (
  id                          bigint generated by default as identity not null,
  throwing_detection_count    smallint null default 0,
  smoking_detection_count     integer  null default 0,
  trespassing_detection_count integer  null default 0,
  created_at timestamp without time zone null default (now() AT TIME ZONE 'Asia/Jakarta'::text),
  constraint frame_detection_count_pkey primary key (id)
) tablespace pg_default;

create table if not exists public.frame_detection_uploaded (
  id                bigint generated by default as identity not null,
  created_at        timestamp with time zone not null default (now() AT TIME ZONE 'Asia/Jakarta'::text),
  throwing_frame    text null,
  smoking_frame     text null,
  trespassing_frame text null,
  constraint result_crime_detection_pkey primary key (id)
) tablespace pg_default;

